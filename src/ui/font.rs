//! Embedded 8x8 bitmap font for ASCII 32-126.
//!
//! Every glyph is written as eight rows of string art (`#` set, `.` clear)
//! and packed into bytes at compile time by [`glyph`]. Bit 7 of each byte
//! is the leftmost pixel. Glyphs use columns 0-6 and leave column 7 blank
//! as inter-character spacing; row 7 is blank except for descenders, so
//! lines can be stacked with no extra leading.
//!
//! Text is drawn with one filled rectangle per set pixel, which is more
//! than fast enough for the few hundred characters an overlay shows.

use sdl2::pixels::Color;
use sdl2::rect::Rect;
use sdl2::render::WindowCanvas;

/// Width and height of a glyph cell in unscaled pixels.
pub const GLYPH_SIZE: u32 = 8;

/// First character in the table.
const FIRST: u8 = 32;
/// Number of characters in the table (ASCII 32 through 126).
const COUNT: usize = 95;

/// Pack eight rows of `#`/`.` art into eight bytes, MSB leftmost.
const fn glyph(rows: [&str; 8]) -> [u8; 8] {
    let mut out = [0u8; 8];
    let mut r = 0;
    while r < 8 {
        let row = rows[r].as_bytes();
        assert!(row.len() == 8, "font row must be eight characters");
        let mut c = 0;
        while c < 8 {
            if row[c] == b'#' {
                out[r] |= 0x80 >> c;
            }
            c += 1;
        }
        r += 1;
    }
    out
}

