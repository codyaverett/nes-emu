/// The bitmap for `ch`. Characters outside ASCII 32-126 draw as `?`.
pub fn glyph_for(ch: char) -> &'static [u8; 8] {
    let index = match ch {
        ' '..='~' => ch as usize - FIRST as usize,
        _ => b'?' as usize - FIRST as usize,
    };
    &FONT[index]
}

/// Width in window pixels of `text` drawn at `scale`.
pub fn text_width(text: &str, scale: u32) -> u32 {
    text.chars().count() as u32 * GLYPH_SIZE * scale
}

/// Height in window pixels of one line of text at `scale`.
pub fn line_height(scale: u32) -> u32 {
    GLYPH_SIZE * scale
}

/// Draw `text` with its top-left corner at (`x`, `y`), each font pixel
/// becoming a `scale` by `scale` block of `colour`.
pub fn draw_text(
    canvas: &mut WindowCanvas,
    x: i32,
    y: i32,
    scale: u32,
    colour: Color,
    text: &str,
) -> Result<(), String> {
    canvas.set_draw_color(colour);
    let step = (GLYPH_SIZE * scale) as i32;
    for (column, ch) in text.chars().enumerate() {
        let origin_x = x + column as i32 * step;
        for (row, bits) in glyph_for(ch).iter().enumerate() {
            let origin_y = y + row as i32 * scale as i32;
            for col in 0..GLYPH_SIZE {
                if bits & (0x80 >> col) != 0 {
                    let px = origin_x + (col * scale) as i32;
                    canvas.fill_rect(Rect::new(px, origin_y, scale, scale))?;
                }
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_printable_ascii() {
        assert_eq!(FONT.len(), 95);
        assert_eq!(glyph_for(' '), &[0u8; 8]);
        // Every glyph except space has at least one pixel set.
        for (i, g) in FONT.iter().enumerate().skip(1) {
            assert!(g.iter().any(|&b| b != 0), "glyph {} is blank", i + 32);
        }
    }

    #[test]
    fn column_seven_is_spacing() {
        for (i, g) in FONT.iter().enumerate() {
            for &row in g {
                assert_eq!(row & 1, 0, "glyph {} uses column 7", i + 32);
            }
        }
    }

    #[test]
    fn packing_is_msb_leftmost() {
        let bang = glyph_for('!');
        assert_eq!(bang[0], 0b0011_0000);
        assert_eq!(bang[5], 0);
        assert_eq!(glyph_for('_')[7], 0b1111_1110);
    }

    #[test]
    fn non_ascii_falls_back_to_question_mark() {
        assert_eq!(glyph_for('\u{e9}'), glyph_for('?'));
        assert_eq!(text_width("abc", 2), 48);
        assert_eq!(line_height(3), 24);
    }
}
